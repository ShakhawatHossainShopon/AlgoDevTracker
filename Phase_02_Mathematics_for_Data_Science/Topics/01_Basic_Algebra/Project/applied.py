import numpy as np

print("=" * 60)
print("📈 শর্ট কোয়ান্ট অ্যালজেব্রা পাইপলাইন (Topic 01 Overview)")
print("=" * 60)

# ------------------------------------------------------------------------------
# ধাপ ১: ভেক্টরাইজড রিটার্ন (Simple & Log Returns)
# ------------------------------------------------------------------------------
prices = np.array([100.0, 102.5, 101.0, 104.0, 106.5])
simple_ret = (prices[1:] - prices[:-1]) / prices[:-1]
log_ret = np.diff(np.log(prices))

print("\n[১] ভেক্টরাইজড রিটার্ন:")
print(f"    • সিম্পল রিটার্ন (%): {np.round(simple_ret * 100, 2)}")
print(f"    • লগ রিটার্ন    (%): {np.round(log_ret * 100, 2)}")

# ------------------------------------------------------------------------------
# ধাপ ২: ব্রডকাস্টিং দিয়ে ফিচার স্কেলিং (Z-Score Standardization)
# ------------------------------------------------------------------------------
# ফিচার: [মোমেন্টাম %, ভলিউম স্পাইক]
X = np.array([
    [ 2.5, 1.8],
    [-1.5, 0.9],
    [ 3.0, 2.2],
    [ 2.4, 1.5]
])

mean = np.mean(X, axis=0)
std = np.std(X, axis=0)
X_scaled = (X - mean) / std

print("\n[২] ব্রডকাস্টিং দিয়ে Z-Score স্কেলিং:")
print(f"    • স্কেলড ফিচার (গড়=০, Std=১):\n{np.round(X_scaled, 2)}")

# ------------------------------------------------------------------------------
# ধাপ ৩: ডট প্রোডাক্ট দিয়ে আলফা স্কোর ও BUY/SELL সিগন্যাল
# ------------------------------------------------------------------------------
weights = np.array([0.7, 0.3])
bias = 0.05

y_pred = X_scaled @ weights + bias
signals = np.where(y_pred > 0, "BUY 🟢", "SELL 🔴")

print("\n[৩] ডট প্রোডাক্ট প্রেডিকশন (y_pred = X @ w + b) ও সিগন্যাল:")
for i in range(len(signals)):
    print(f"    ক্যান্ডেল #{i+1}: প্রেডিক্ট মুভ = {y_pred[i]:>+5.2f}% | সিগন্যাল = {signals[i]}")

# ------------------------------------------------------------------------------
# ধাপ ৪: ট্রেন্ডলাইন ও প্রাইজ ভেলোসিটি (Trendline: y = mx + c)
# ------------------------------------------------------------------------------
x = np.arange(len(prices))
slope, intercept = np.polyfit(x, prices, deg=1)

print("\n[৪] ট্রেন্ডলাইন ও মোমেন্টাম ঢাল:")
print(f"    • সমীকরণ: Price = ({slope:+.2f}) * Bar + {intercept:.2f}")
print(f"    • গতি (Slope): {slope:+.2f} পয়েন্ট/ক্যান্ডেল ({'আপট্রেন্ড 🚀' if slope > 0 else 'ডাউনট্রেন্ড 🔻'})")
print("\n" + "=" * 60)
